"""
algo_trading/research/market_maker.py — Paper-mode Avellaneda-Stoikov market making.

IMPORTANT: This module is RESEARCH/PAPER MODE ONLY.
Live market making requires:
  - True low-latency infrastructure (co-location or Mumbai VPS with <5ms to NSE)
  - Exchange approval for algo market making
  - Significant capital (lot sizes in F&O are large)
  - Understanding of adverse selection risk

This implements the Avellaneda-Stoikov (2008) model for RESEARCH simulation:
  - Computes optimal bid/ask quotes given inventory, risk aversion, and volatility
  - Simulates quote fills and inventory accumulation
  - Tracks P&L, spread capture, and cancel ratio

Metrics tracked:
  - Spread capture rate: how often both sides fill (earn the spread)
  - Adverse selection rate: fills that result in immediate losses
  - OTR (Order-to-Trade Ratio): should stay < 20:1 (NSE guidelines)
  - Cancel ratio: cancelled orders / total orders

References:
  Avellaneda, M. & Stoikov, S. (2008). High-frequency trading in a limit order book.
  Guéant, O. (2017). Optimal market making.

All parameter values marked [ASSUMED] must be calibrated before drawing
conclusions about strategy edge.
"""
from __future__ import annotations

import math
import random
from dataclasses import dataclass, field
from typing import Any, Optional

import structlog

log = structlog.get_logger(__name__)


# ---------------------------------------------------------------------------
# Configuration and state dataclasses
# ---------------------------------------------------------------------------

@dataclass
class MarketMakerConfig:
    """Configuration for the Avellaneda-Stoikov paper market maker.

    Attributes:
        gamma: Risk-aversion parameter (0=risk-neutral, 1=highly risk-averse).
            Higher gamma → tighter spread when inventory is low, faster skew
            when inventory builds.  [ASSUMED 0.1 for NSE liquid large-cap]
        sigma: Price volatility per unit time (same units as T).
            [ASSUMED 0.02 = 2% per session for NSE large-cap]
        T: Time horizon (1.0 = full session end). t_remaining is normalised
            against this value.
        k: Order book depth / fill intensity parameter.  Higher k means a
            shallower book (harder to fill).  [ASSUMED 1.5 for NSE large-cap]
        max_inventory: Maximum net position in lots before aggressive skew kicks in.
            [ASSUMED 10 lots]
        min_spread_bps: Minimum quoted spread in basis points.  Prevents quoting
            tighter than the exchange tick. [ASSUMED 5 bps]
        quote_refresh_bars: Re-quote every N bars (currently unused for pacing;
            on_bar() always re-quotes).
        otr_limit: Maximum order-to-trade ratio before halting.
            NSE guideline: < 20:1. [ASSUMED 20.0]
    """

    gamma: float = 0.1
    sigma: float = 0.02
    T: float = 1.0
    k: float = 1.5
    max_inventory: int = 10
    min_spread_bps: float = 5.0
    quote_refresh_bars: int = 1
    otr_limit: float = 20.0


@dataclass
class Quote:
    """A bid/ask quote pair generated by the market maker.

    Attributes:
        bid_price: Quoted bid price in INR.
        ask_price: Quoted ask price in INR.
        bid_qty: Quantity offered at the bid.
        ask_qty: Quantity offered at the ask.
        timestamp: Bar timestamp (datetime or bar index).
        reservation_price: Avellaneda-Stoikov reservation price used to centre
            the quote.  r = mid - gamma * sigma^2 * inventory * T_remaining.
        quoted_spread: ask_price - bid_price in INR.
    """

    bid_price: float
    ask_price: float
    bid_qty: int
    ask_qty: int
    timestamp: Any
    reservation_price: float
    quoted_spread: float


@dataclass
class MarketMakerSnapshot:
    """Cumulative state of the paper market maker at a point in time.

    Attributes:
        timestamp: Bar timestamp.
        inventory: Net position (positive = long, negative = short).
        cumulative_pnl: Total realised P&L from completed round trips in INR.
        spread_capture_count: Number of bars where both bid and ask filled
            (full spread earned).
        adverse_selection_count: Number of fills followed by immediate adverse
            price movement (simulated).
        total_quotes: Total quote-side orders submitted (bids + asks).
        total_fills: Total fill events (one per side).
        total_cancels: Total cancel events (old quotes cancelled before re-quoting).
        otr: Current order-to-trade ratio = (total_quotes + total_cancels) / max(1, total_fills).
    """

    timestamp: Any
    inventory: int
    cumulative_pnl: float
    spread_capture_count: int
    adverse_selection_count: int
    total_quotes: int
    total_fills: int
    total_cancels: int
    otr: float


# ---------------------------------------------------------------------------
# PaperMarketMaker
# ---------------------------------------------------------------------------

class PaperMarketMaker:
    """Paper-mode Avellaneda-Stoikov market maker.

    Takes OHLC mid-prices as input, computes optimal bid/ask quotes, and
    simulates fills using a simple probabilistic fill model:

      - Bid fills if bar_low <= bid_price (price dipped to our bid).
      - Ask fills if bar_high >= ask_price (price rose to our ask).
      - Adverse selection: 30% of fills are "toxic" — price continues moving
        against inventory after the fill.  [ASSUMED]

    RESEARCH/PAPER MODE ONLY — see module docstring.

    Args:
        config: MarketMakerConfig.  Uses defaults if None.
        seed: Random seed for reproducible simulation.

    Example::

        mm = PaperMarketMaker()
        for bar in ohlc_bars:
            t_remaining = bar.minutes_remaining / 375.0
            snapshot = mm.on_bar(
                bar_mid=bar.mid, bar_high=bar.high,
                bar_low=bar.low, t_remaining=t_remaining
            )
        report = mm.get_spread_capture_report()
    """

    def __init__(
        self,
        config: Optional[MarketMakerConfig] = None,
        seed: int = 42,
    ) -> None:
        self._config = config or MarketMakerConfig()
        self._rng = random.Random(seed)

        # Running state
        self._inventory: int = 0
        self._cumulative_pnl: float = 0.0
        self._spread_capture_count: int = 0
        self._adverse_selection_count: int = 0
        self._total_quotes: int = 0
        self._total_fills: int = 0
        self._total_cancels: int = 0

        # Pending quote from previous bar (may still be live)
        self._pending_quote: Optional[Quote] = None
        self._bar_idx: int = 0

        log.info(
            "paper_market_maker.init",
            gamma=self._config.gamma,
            sigma=self._config.sigma,
            k=self._config.k,
            max_inventory=self._config.max_inventory,
        )

    # -------------------------------------------------------------------------
    # Avellaneda-Stoikov core formulas
    # -------------------------------------------------------------------------

    def compute_reservation_price(
        self,
        mid: float,
        inventory: int,
        t_remaining: float,
    ) -> float:
        """Compute the Avellaneda-Stoikov reservation (indifference) price.

        The reservation price is the mid adjusted for the cost of holding
        current inventory over the remaining session time::

            r = mid - gamma * sigma^2 * inventory * T_remaining

        Args:
            mid: Current mid-price in INR.
            inventory: Current net inventory (positive = long).
            t_remaining: Fraction of session remaining (0.0 = expired, 1.0 = full).

        Returns:
            Reservation price in INR.
        """
        t_rem = max(0.0, min(t_remaining, self._config.T))
        reservation = (
            mid
            - self._config.gamma
            * (self._config.sigma ** 2)
            * inventory
            * t_rem
        )
        return reservation

    def compute_optimal_spread(self, t_remaining: float) -> float:
        """Compute the optimal half-spread from the Avellaneda-Stoikov model.

        Formula (Avellaneda & Stoikov 2008, eq. 14)::

            optimal_half_spread = gamma * sigma^2 * T_remaining
                                  + (2/gamma) * ln(1 + gamma/k)

        Args:
            t_remaining: Fraction of session remaining (0 = expired, 1 = full).

        Returns:
            Optimal half-spread in price units (same units as mid).

        Notes:
            The returned half-spread is at least min_spread_bps / 10000 * mid
            (enforced by generate_quote, not here, since mid is not available).
        """
        t_rem = max(0.0, min(t_remaining, self._config.T))
        gamma = self._config.gamma
        k = self._config.k

        # Avoid log(1 + gamma/k) domain error — k must be > 0
        if k <= 0 or gamma <= 0:
            return 0.0

        half_spread = (
            gamma * (self._config.sigma ** 2) * t_rem
            + (2.0 / gamma) * math.log(1.0 + gamma / k)
        )
        return max(half_spread, 0.0)

    def generate_quote(
        self,
        mid: float,
        inventory: int,
        t_remaining: float,
    ) -> Quote:
        """Generate an optimal bid/ask quote pair.

        When inventory is at or near max_inventory, the quote is skewed
        aggressively to reduce inventory:
          - Long skew: tighten the ask, widen the bid (encourage selling).
          - Short skew: tighten the bid, widen the ask (encourage buying).

        The minimum spread floor (min_spread_bps) is always enforced.

        Args:
            mid: Current mid-price in INR.
            inventory: Current net inventory.
            t_remaining: Fraction of session remaining.

        Returns:
            Quote dataclass with bid/ask prices and metadata.
        """
        cfg = self._config

        reservation = self.compute_reservation_price(mid, inventory, t_remaining)
        half_spread = self.compute_optimal_spread(t_remaining)

        # Minimum spread floor (basis points → price units)
        min_half_spread = (cfg.min_spread_bps / 10_000.0) * mid / 2.0
        half_spread = max(half_spread, min_half_spread)

        bid = reservation - half_spread
        ask = reservation + half_spread

        # Inventory skew: if at max, aggressively skew to reduce
        inv_fraction = abs(inventory) / max(cfg.max_inventory, 1)
        if inv_fraction >= 1.0:
            skew_factor = 3.0   # 3× half_spread skew when at max [ASSUMED]
            if inventory > 0:
                # Long inventory: push ask much tighter, widen bid
                ask = reservation + half_spread * 0.25
                bid = reservation - half_spread * skew_factor
            else:
                # Short inventory: push bid much tighter, widen ask
                bid = reservation + half_spread * 0.25
                ask = reservation + half_spread * skew_factor
        elif inv_fraction > 0.5:
            # Moderate skew
            skew = half_spread * inv_fraction
            if inventory > 0:
                ask = ask - skew * 0.5
                bid = bid - skew * 0.5
            else:
                ask = ask + skew * 0.5
                bid = bid + skew * 0.5

        # Ensure ask > bid with at least the minimum spread
        if ask <= bid:
            mid_point = (bid + ask) / 2.0
            ask = mid_point + min_half_spread
            bid = mid_point - min_half_spread

        quote = Quote(
            bid_price=max(0.0, bid),
            ask_price=max(0.0, ask),
            bid_qty=1,   # 1 lot per side [ASSUMED]
            ask_qty=1,
            timestamp=self._bar_idx,
            reservation_price=reservation,
            quoted_spread=ask - bid,
        )
        log.debug(
            "paper_market_maker.quote_generated",
            bar_idx=self._bar_idx,
            mid=round(mid, 2),
            reservation=round(reservation, 4),
            bid=round(quote.bid_price, 4),
            ask=round(quote.ask_price, 4),
            spread=round(quote.quoted_spread, 4),
            inventory=inventory,
        )
        return quote

    # -------------------------------------------------------------------------
    # Bar update
    # -------------------------------------------------------------------------

    def on_bar(
        self,
        bar_mid: float,
        bar_high: float,
        bar_low: float,
        t_remaining: float,
    ) -> MarketMakerSnapshot:
        """Update state for one bar: check fills, then re-quote.

        Fill model:
          - Bid fills if bar_low <= bid_price.
          - Ask fills if bar_high >= ask_price.
          - Adverse selection (30% probability [ASSUMED]): if a fill occurs
            and price continues adversely, flag as adverse_selection.

        Inventory liquidation rule:
          - If abs(inventory) >= max_inventory, quotes are skewed aggressively
            (handled in generate_quote).

        Halt check:
          - If should_halt_quoting() returns True, no new quote is generated
            this bar.

        Args:
            bar_mid: Bar mid-price (e.g. (high + low) / 2) in INR.
            bar_high: Bar high price in INR.
            bar_low: Bar low price in INR.
            t_remaining: Fraction of session remaining at bar open.

        Returns:
            MarketMakerSnapshot with current state after this bar.
        """
        self._bar_idx += 1

        # ── Step 1: Check fills on pending quote ──────────────────────────────
        bid_filled = False
        ask_filled = False

        if self._pending_quote is not None:
            pq = self._pending_quote

            # Cancel the old quote (will be replaced)
            self._total_cancels += 1

            if bar_low <= pq.bid_price:
                # Bid got hit — we bought
                bid_filled = True
                self._inventory += pq.bid_qty
                self._cumulative_pnl -= pq.bid_price * pq.bid_qty
                self._total_fills += 1

                # Adverse selection: 30% of fills are toxic [ASSUMED]
                if self._rng.random() < 0.30:
                    # Price continued down after our buy — loss
                    adverse_loss = pq.bid_price * pq.bid_qty * 0.001  # 10bps adverse [ASSUMED]
                    self._cumulative_pnl -= adverse_loss
                    self._adverse_selection_count += 1
                    log.debug(
                        "paper_market_maker.adverse_selection.bid",
                        bar_idx=self._bar_idx,
                        loss=round(adverse_loss, 4),
                    )

            if bar_high >= pq.ask_price:
                # Ask got lifted — we sold
                ask_filled = True
                self._inventory -= pq.ask_qty
                self._cumulative_pnl += pq.ask_price * pq.ask_qty
                self._total_fills += 1

                # Adverse selection: 30% of fills are toxic [ASSUMED]
                if self._rng.random() < 0.30:
                    # Price continued up after our sell — loss
                    adverse_loss = pq.ask_price * pq.ask_qty * 0.001  # 10bps adverse [ASSUMED]
                    self._cumulative_pnl -= adverse_loss
                    self._adverse_selection_count += 1
                    log.debug(
                        "paper_market_maker.adverse_selection.ask",
                        bar_idx=self._bar_idx,
                        loss=round(adverse_loss, 4),
                    )

            # Spread capture: both sides filled this bar
            if bid_filled and ask_filled:
                self._spread_capture_count += 1
                log.debug(
                    "paper_market_maker.spread_capture",
                    bar_idx=self._bar_idx,
                    spread=round(pq.quoted_spread, 4),
                )

        # ── Step 2: Check halt condition ──────────────────────────────────────
        halt, halt_reason = self.should_halt_quoting()
        if halt:
            log.warning(
                "paper_market_maker.halted",
                bar_idx=self._bar_idx,
                reason=halt_reason,
            )
            self._pending_quote = None
        else:
            # ── Step 3: Generate new quote ────────────────────────────────────
            new_quote = self.generate_quote(bar_mid, self._inventory, t_remaining)
            self._pending_quote = new_quote
            self._total_quotes += 2  # bid + ask sides

        return self._build_snapshot()

    # -------------------------------------------------------------------------
    # Reporting
    # -------------------------------------------------------------------------

    def get_spread_capture_report(self) -> dict:
        """Generate a summary performance report for the paper market maker.

        Returns:
            Dictionary with keys:
              - total_pnl (float): Cumulative realised P&L in INR.
              - spread_capture_rate (float): Fraction of bars where both sides filled.
              - adverse_selection_rate (float): Fraction of fills that were adverse.
              - otr (float): Current order-to-trade ratio.
              - cancel_ratio (float): Cancels / total_quotes.
              - total_fills (int): Total fill events.
              - total_quotes (int): Total quote submissions.
              - total_cancels (int): Total cancel events.
              - final_inventory (int): Net inventory at report time.
        """
        total_bars = max(1, self._bar_idx)
        otr = (self._total_quotes + self._total_cancels) / max(1, self._total_fills)
        spread_capture_rate = self._spread_capture_count / total_bars
        adverse_rate = self._adverse_selection_count / max(1, self._total_fills)
        cancel_ratio = self._total_cancels / max(1, self._total_quotes)

        report = {
            "total_pnl": round(self._cumulative_pnl, 4),
            "spread_capture_rate": round(spread_capture_rate, 4),
            "adverse_selection_rate": round(adverse_rate, 4),
            "otr": round(otr, 4),
            "cancel_ratio": round(cancel_ratio, 4),
            "total_fills": self._total_fills,
            "total_quotes": self._total_quotes,
            "total_cancels": self._total_cancels,
            "final_inventory": self._inventory,
        }
        log.info("paper_market_maker.spread_capture_report", **report)
        return report

    def should_halt_quoting(self) -> tuple[bool, str]:
        """Determine whether the market maker should stop quoting.

        Halt conditions:
          1. OTR > otr_limit (NSE guideline: < 20:1).
          2. abs(inventory) >= max_inventory AND no fills in last bar
             (inventory is stuck — unwind manually).

        Returns:
            Tuple (should_halt: bool, reason: str).  reason is empty if not halting.
        """
        otr = (self._total_quotes + self._total_cancels) / max(1, self._total_fills)

        if otr > self._config.otr_limit:
            reason = (
                f"OTR {otr:.1f} exceeds NSE limit {self._config.otr_limit:.1f}. "
                "Halting to avoid exchange penalty."
            )
            log.warning(
                "paper_market_maker.halt.otr_exceeded",
                otr=round(otr, 2),
                limit=self._config.otr_limit,
            )
            return True, reason

        if abs(self._inventory) >= self._config.max_inventory and self._total_fills == 0:
            reason = (
                f"Inventory stuck at max ({self._inventory} lots) with no fills. "
                "Halting to prevent further position accumulation."
            )
            log.warning(
                "paper_market_maker.halt.inventory_stuck",
                inventory=self._inventory,
                max_inventory=self._config.max_inventory,
            )
            return True, reason

        return False, ""

    # -------------------------------------------------------------------------
    # Internal helpers
    # -------------------------------------------------------------------------

    def _build_snapshot(self) -> MarketMakerSnapshot:
        """Build a MarketMakerSnapshot from current internal state.

        Returns:
            MarketMakerSnapshot with all current counters and metrics.
        """
        otr = (self._total_quotes + self._total_cancels) / max(1, self._total_fills)
        return MarketMakerSnapshot(
            timestamp=self._bar_idx,
            inventory=self._inventory,
            cumulative_pnl=self._cumulative_pnl,
            spread_capture_count=self._spread_capture_count,
            adverse_selection_count=self._adverse_selection_count,
            total_quotes=self._total_quotes,
            total_fills=self._total_fills,
            total_cancels=self._total_cancels,
            otr=otr,
        )
